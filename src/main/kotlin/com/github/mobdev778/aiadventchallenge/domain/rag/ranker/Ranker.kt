package com.github.mobdev778.aiadventchallenge.domain.rag.ranker

/**
 * Интерфейс компонента ранжирования (Ranker) в конвейере RAG (Retrieval-Augmented Generation).
 *
 * Отвечает за оценку релевантности найденных фрагментов документа относительно исходного запроса
 * пользователя. Ранкер инициализируется один раз для запроса, после чего может многократно
 * использоваться для вычисления скоров для различных найденных фрагментов. Итоговая оценка
 * в виде числа с плавающей точкой позволяет сортировать результаты и отбирать наиболее
 * релевантные для последующей генерации ответа.
 *
 * Все методы являются приостанавливаемыми ([suspend]) и должны вызываться в контексте корутины.
 */
interface Ranker {

    /**
     * Инициализирует ранкер для обработки указанного запроса.
     *
     * Вызывается однократно перед серией вызовов [rank]. На этом этапе компонент может
     * выполнить ресурсоёмкую подготовку — например, вычислить эмбеддинг запроса или
     * предзагрузить необходимые модели.
     *
     * @param query текстовый запрос пользователя, относительно которого будет оцениваться
     *              релевантность найденных фрагментов
     */
    suspend fun init(query: String)

    /**
     * Вычисляет оценку релевантности найденного фрагмента документа.
     *
     * На вход подаётся текст фрагмента и его предварительно вычисленное векторное представление.
     * Метод возвращает числовую оценку (как правило, от 0 до 1), где более высокое значение
     * соответствует большей релевантности фрагмента запросу, переданному в [init].
     *
     * @param found текст найденного фрагмента документа-кандидата
     * @param vector векторное представление (эмбеддинг) данного фрагмента, используемое
     *               для семантического сопоставления с запросом
     * @return числовая оценка релевантности фрагмента; чем выше значение, тем более
     *         релевантен фрагмент исходному запросу
     */
    suspend fun rank(found: String, vector: FloatArray): Double
}
