package com.github.mobdev778.aiadventchallenge.domain.task

/**
 * Состояния жизненного цикла задачи в рамках доменной логики приложения.
 * Используется для управления процессом выполнения задачи от планирования до завершения.
 */
enum class TaskState {
    /**
     * Стадия сбора требований и утверждения плана.
     */
    Planning,    // собираем требования, утверждаем план

    /**
     * Стадия непосредственного выполнения задачи (написание кода, создание артефактов).
     */
    Execution,   // выполняем задачу (пишем код, создаем артефакты)

    /**
     * Стадия проверки результатов: тестирование, ревью, верификация соответствия плану.
     */
    Validation,  // тесты, ревью, соответствие плану

    /**
     * Стадия вывода итогового результата.
     */
    PrintResult, // выведи результат

    /**
     * Финальная стадия: задача полностью завершена.
     */
    Done,        // задача завершена
}
