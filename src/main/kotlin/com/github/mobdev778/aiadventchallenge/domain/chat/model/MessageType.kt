package com.github.mobdev778.aiadventchallenge.domain.chat.model

/**
 * Перечисление, определяющее тип сообщения в системе чата.
 *
 * Используется для классификации сообщений внутри доменной модели чата,
 * что позволяет различать источник и назначение каждого сообщения:
 * ввод пользователя, ответ ассистента, вызов инструмента или
 * системные закреплённые факты.
 */
enum class MessageType {

    /** Сообщение, отправленное пользователем. */
    User,

    /** Сообщение, сгенерированное ассистентом (ботом) в ответ на запрос. */
    Bot,

    /** Сообщение, связанное с вызовом внешнего инструмента или функции. */
    Tool,

    /** Закреплённые факты — служебный тип, содержащий контекстную информацию,
     * которая должна сохраняться в истории диалога. */
    StickyFacts,
}
