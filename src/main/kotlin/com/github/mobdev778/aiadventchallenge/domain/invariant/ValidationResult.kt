package com.github.mobdev778.aiadventchallenge.domain.invariant

/**
 * Запечатанный класс, представляющий результат проверки инварианта
 * (бизнес-правила, валидации). Используется для единообразной обработки
 * успешного и неуспешного исходов проверки в доменном слое.
 *
 * Наследники:
 * - [Passed] — проверка пройдена успешно.
 * - [Failed] — проверка не пройдена, содержит причину отказа.
 */
sealed class ValidationResult {
    /**
     * Успешное прохождение проверки. Обозначает, что инвариант соблюдён
     * и бизнес-правило не нарушено.
     */
    object Passed : ValidationResult()

    /**
     * Неуспешное прохождение проверки.
     *
     * @property reason Человекочитаемое описание причины, по которой
     * проверка не была пройдена (например, "Баланс не может быть отрицательным").
     */
    data class Failed(val reason: String) : ValidationResult()
}
