package com.github.mobdev778.aiadventchallenge.domain.agent.agents.document

import com.intellij.psi.PsiFileSystemItem

/**
 * Узел графа, представляющий элемент файловой системы (файл или директорию),
 * используемый для отслеживания связей и состояния документирования.
 *
 * Данный класс является частью внутреннего графа, который строится
 * в процессе анализа и документирования кодовой базы.
 *
 * @property path путь к элементу в проекте
 * @property item PSI-элемент файловой системы (файл или директория)
 */
class KtGraphNode(val path: String, val item: PsiFileSystemItem) {

    /**
     * Флаг, показывающий, был ли узел уже посещён в процессе обхода графа.
     */
    var visited = false

    /**
     * Отметка о том, задокументирован ли данный элемент.
     * `true` означает, что документация для элемента уже была сгенерирована.
     */
    var documented: Boolean = false

    /**
     * Текстовое описание узла, заполняемое в процессе анализа.
     */
    var description: String = ""

    /**
     * Множество узлов, на которые ссылается данный элемент (ребра графа).
     */
    val links = HashSet<KtGraphNode>()

}
