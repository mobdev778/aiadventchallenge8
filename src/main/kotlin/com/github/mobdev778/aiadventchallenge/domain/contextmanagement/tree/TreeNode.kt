package com.github.mobdev778.aiadventchallenge.domain.contextmanagement.tree

import com.github.mobdev778.aiadventchallenge.domain.chat.model.ChatMessage

/**
 * Узел бинарного дерева диалога, представляющий собой одно сообщение чата.
 *
 * Используется для построения древовидной структуры диалоговых веток. Каждый узел
 * хранит ссылку на модель [ChatMessage] и может иметь до двух дочерних узлов:
 * левого и правого. Левое поддерево соответствует первой альтернативной ветке,
 * правое — второй. Структура позволяет переключаться между вариантами продолжения
 * диалога (см. [ChatMessage.branchB]), а также обеспечивает эффективный обход
 * и поиск сообщений в контексте управления диалоговым деревом.
 *
 * @property value Сообщение, хранящееся в данном узле дерева.
 */
class TreeNode(val value: ChatMessage) {
    /**
     * Левый дочерний узел (одна из альтернативных веток продолжения диалога).
     * Может быть `null`, если левая ветка отсутствует.
     */
    var left: TreeNode? = null

    /**
     * Правый дочерний узел (вторая альтернативная ветка продолжения диалога).
     * Может быть `null`, если правая ветка отсутствует.
     */
    var right: TreeNode? = null
}
