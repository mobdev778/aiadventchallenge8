package com.github.mobdev778.aiadventchallenge.domain.rag.model

import java.util.UUID

/**
 * Документ, используемый в системе RAG (Retrieval-Augmented Generation).
 *
 * Представляет собой единицу данных, которая может быть проиндексирована,
 * найдена по релевантности и передана в качестве контекста генеративной модели.
 * Каждый документ обладает уникальным идентификатором, указанием на источник
 * происхождения и читаемым заголовком.
 *
 * @property id Уникальный идентификатор документа.
 * @property source Источник, из которого был получен документ (например, путь к файлу, URL, название базы данных).
 * @property title Заголовок документа, предназначенный для отображения и быстрой идентификации содержимого.
 */
data class RagDocument(
    val id: UUID,
    val source: String,
    val title: String,
)
