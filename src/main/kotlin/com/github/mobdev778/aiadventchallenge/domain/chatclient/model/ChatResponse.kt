package com.github.mobdev778.aiadventchallenge.domain.chatclient.model

/**
 * Модель ответа от Chat API, содержащая список вариантов сгенерированных сообщений и метаданные об использовании токенов.
 *
 * Экземпляр этого класса возвращается после вызова языковой модели. Он объединяет все возможные ответы ([Choice]),
 * а также сводку по израсходованным токенам ([Usage]), что позволяет отслеживать затраты и лимиты.
 *
 * @property choices Список вариантов ответа. Каждый [Choice] включает сгенерированное [Message] и причину остановки генерации.
 * @property usage Информация об использованных токенах запроса и ответа. Может быть `null`, если API не предоставило эти данные (например, при ошибке).
 */
data class ChatResponse(
    val choices: List<Choice>,
    val usage: Usage?,
)
