package com.github.mobdev778.aiadventchallenge.domain.rag.model

/**
 * Тип фильтра, используемого в процессе RAG (Retrieval-Augmented Generation).
 *
 * Определяет стратегию отбора и упорядочивания релевантных документов
 * перед их передачей в генеративную модель. Каждый тип фильтра
 * соответствует определённому алгоритмическому подходу к ранжированию
 * результатов поиска.
 */
enum class RagFilterType {

    /**
     * Фильтрация на основе косинусного или иного векторного сходства
     * между запросом и документами. Наиболее простой и быстрый метод,
     * использующий исключительно эмбеддинги.
     */
    Similarity,

    /**
     * Фильтрация с применением модели-реранкера (reranker).
     * Использует специализированную кросс-энкодерную модель для
     * более точной оценки релевантности пары «запрос – документ».
     * Обеспечивает более высокое качество отбора по сравнению
     * с обычным сходством, но требует дополнительных вычислительных затрат.
     */
    Reranker,

    /**
     * Эвристическая фильтрация, основанная на наборе правил,
     * задаваемых вручную или вычисляемых на основе метаданных.
     * Позволяет учитывать доменно-специфичные критерии,
     * не охватываемые модельными методами.
     */
    Heuristic,
}
