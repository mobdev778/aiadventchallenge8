package com.github.mobdev778.aiadventchallenge.domain.agent.model

/**
 * Тип агента, определяющий его роль и функциональные обязанности в системе.
 *
 * Каждое значение перечисления соответствует специализированному агенту,
 * участвующему в конвейере обработки запросов, планирования, выполнения,
 * валидации и документирования.
 */
enum class AgentType {
    /** Простой диалоговый агент, реализующий базовое общение. */
    ChatAssistant,

    /** Агент-планировщик, отвечающий за составление плана действий. */
    Planner,

    /** Агент-исполнитель, непосредственно выполняющий шаги плана. */
    Executor,

    /** Агент-валидатор, проверяющий корректность результатов выполнения. */
    Validator,

    /** Агент, подводящий итоги и формирующий сводки. */
    Summarizer,

    /** Агент, документирующий структуру и состояние проекта. */
    DocumentProject,

    /** Агент, подготавливающий черновую версию файла документации. */
    DraftDocumentFile,

    /** Агент, работающий с финальными файлами документации. */
    DocumentFile,

    /** Агент, отвечающий на вопросы о проекте */
    Help,
}
