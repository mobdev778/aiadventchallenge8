package com.github.mobdev778.aiadventchallenge.domain.invariant

/**
 * Абстрактный базовый класс для инвариантов валидации.
 *
 * Инвариант представляет собой правило, которое должно выполняться при обработке
 * пары "запрос-ответ". Каждый инвариант имеет уникальный идентификатор, описание,
 * понятное для LLM, и метод проверки, возвращающий [ValidationResult].
 */
abstract class Invariant {

    /**
     * Уникальный идентификатор инварианта.
     */
    abstract val id: String

    /**
     * Описание инварианта, предназначенное для передачи контекста в языковую модель (LLM).
     */
    abstract val llmDescription: String // описание инварианта для LLM

    /**
     * Проверяет, удовлетворяет ли ответ заданному инварианту.
     *
     * Передаются и запрос пользователя, и ответ бота для полной картины взаимодействия.
     *
     * @param request текст запроса пользователя
     * @param response текст ответа бота
     * @return результат валидации, содержащий вердикт и детали
     */
    abstract fun validate(request: String, response: String): ValidationResult
}
