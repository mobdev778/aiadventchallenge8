package com.github.mobdev778.aiadventchallenge.domain.imagegenerator

import java.awt.image.BufferedImage

/**
 * Интерфейс генератора изображений, определяющий контракт для сервисов,
 * которые создают растровые изображения на основе текстового описания.
 *
 * Реализации данного интерфейса могут использовать различные источники
 * генерации (нейросети, API сторонних сервисов и т.д.). Интерфейс является
 * частью доменного слоя и абстрагирует вышележащие слои от конкретных
 * деталей реализации генерации изображений.
 */
interface ImageGenerator {

    /**
     * Генерирует изображение на основе переданного текстового запроса
     * с заданным уровнем креативности (температуры).
     *
     * @param temperature степень случайности/креативности генерации.
     *   Значение в диапазоне от 0.0 (строгое следование промпту) до 1.0 и выше
     *   (максимальная вариативность результата).
     * @param userPrompt текстовое описание желаемого изображения,
     *   составленное пользователем.
     * @return сгенерированное растровое изображение в виде объекта [BufferedImage].
     */
    suspend fun generateImage(
        temperature: Double,
        userPrompt: String,
    ): BufferedImage
}
