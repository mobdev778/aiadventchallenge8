package com.github.mobdev778.aiadventchallenge.domain.chatclient.model

/**
 * Представляет сообщение в диалоге с языковой моделью.
 *
 * Экземпляры этого класса используются как строительные блоки для передачи истории переписки
 * и инструкций модели. Каждое сообщение содержит [роль][role], определяющую источник сообщения,
 * а также может включать текстовое содержимое, вызовы инструментов, идентификатор вызова
 * инструмента или имя функции.
 *
 * @param role Роль автора сообщения (например, system, user, assistant, tool). См. [Role].
 * @param content Текстовое содержимое сообщения. Может быть `null`, если сообщение представляет
 *                только вызов инструмента или результат его выполнения.
 * @param toolCalls Список вызовов инструментов, инициированных моделью (только для роли assistant).
 *                  По умолчанию `null`. Каждый вызов описывается объектом [ToolCall].
 * @param toolCallId Идентификатор вызова инструмента, на который отвечает данное сообщение
 *                    (обычно используется при роли tool). По умолчанию `null`.
 * @param name Имя функции (инструмента), чей результат возвращается в сообщении с ролью tool
 *             (в некоторых API). По умолчанию `null`.
 */
data class Message(
    val role: Role,
    val content: String?,
    val toolCalls: List<ToolCall>? = null,
    val toolCallId: String? = null,
    val name: String? = null
)
