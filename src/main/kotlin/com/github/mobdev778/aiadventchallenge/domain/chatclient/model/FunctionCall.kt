package com.github.mobdev778.aiadventchallenge.domain.chatclient.model

/**
 * Представляет вызов функции, инициированный моделью искусственного интеллекта.
 *
 * Этот класс используется для передачи информации о вызываемой функции и её аргументах
 * в рамках механизма "function calling" при взаимодействии с языковыми моделями.
 * Экземпляры [FunctionCall] создаются на основе ответов от AI-сервисов и содержат
 * все необходимые данные для последующего выполнения соответствующей функции в системе.
 *
 * @property name Имя вызываемой функции, соответствующее идентификатору, зарегистрированному в системе.
 * @property arguments Строка в формате JSON, содержащая фактические аргументы для вызова функции.
 */
data class FunctionCall(
    val name: String,
    val arguments: String // JSON-строка с аргументами
)
