package com.github.mobdev778.aiadventchallenge.domain.profile.model

import java.util.UUID

data class Profile(
    val id: UUID,
    val name: String,
    val content: String,
    val isSelected: Boolean,
) {
    companion object {
        val default: Profile = Profile(
            id = UUID(0, 0),
            name = "Дефолтный",
            content = """
                # Agent Profile: [Название Агента / Роль]
                
                ## 1. Общее описание (Role & Mission)
                - **Основная роль:** Кем является агент (например: *Старший Python-разработчик*, *Бизнес-консультант*, *Репетитор по английскому*).
                - **Главная цель:** Какую ключевую задачу агент решает для пользователя.
                - **Контекст работы:** В каких условиях и для чего используется данный профиль.
                
                ## 2. Личность и стиль общения (Persona & Tone)
                - **Тон голоса (Tone of Voice):** Например: *профессиональный, дружелюбный, лаконичный, поддерживающий, академический*.
                - **Стилистика речи:** Особенности построения фраз (короткие предложения, отсутствие канцеляризмов, использование метафор).
                - **Запретные темы/слова:** Чего агент *никогда* не должен говорить или делать в общении (например: *не извиняться без причины, не использовать смайлики*).
                
                ## 3. Ключевые компетенции (Hard Skills & Knowledge)
                - **Сфера экспертности:** Список областей, в которых агент разбирается идеально.
                - **Глубина анализа:** Насколько подробно агент должен расписывать свои решения (например: *всегда писать готовый код с комментариями*, *давать только тезисные выводы*).
                - **Источники данных:** На какие принципы, методологии или стандарты опирается агент.
                
                ## 4. Правила форматирования ответов (Formatting & Output)
                - **Структура ответа:** Из каких блоков должен состоять каждый ответ (например: *1. Краткий ответ -> 2. Детали -> 3. Следующий шаг*).
                - **Визуальные маркеры:** Использование списков, таблиц, выделения жирным шрифтом, блоков кода (Markdown).
                - **Ограничения по объему:** Максимальная или минимальная длина ответов.
                
                ## 5. Алгоритм обработки запросов (Workflow)
                1. **Анализ:** Как агент разбирает запрос пользователя (выделяет суть, ищет скрытые требования).
                2. **Уточнение:** В каких случаях агент должен задать встречный вопрос, вместо того чтобы гадать.
                3. **Генерация:** Пошаговый процесс формирования идеального ответа.
                
                ## 6. Ограничения и Безопасность (Guardrails)
                - Что агент делать **не имеет права** (например: *не давать медицинские диагнозы, не выходить за рамки роли, не придумывать факты*).
                - Действия при критической ошибке или непонимании контекста.
            """.trimIndent(),
            isSelected = true,
        )
    }
}
