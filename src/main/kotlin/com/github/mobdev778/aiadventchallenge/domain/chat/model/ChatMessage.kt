package com.github.mobdev778.aiadventchallenge.domain.chat.model

import java.util.UUID

/**
 * Модель данных сообщения в чате.
 *
 * Представляет собой отдельное сообщение внутри определённого чата, хранящее все необходимые
 * метаданные: уникальный идентификатор, текст, временную метку, тип отправителя (пользователь,
 * бот, инструмент, закреплённый факт), информацию о ветвлении диалога и количестве использованных
 * токенов. Каждое сообщение может быть частью древовидной структуры диалога, что позволяет
 * отслеживать альтернативные ветки ответов ассистента.
 *
 * @property id Уникальный идентификатор сообщения.
 * @property chatId Идентификатор чата, к которому относится сообщение.
 * @property parentId Идентификатор родительского сообщения (опциональный), используется для построения
 *                   диалогового дерева. Если сообщение является корневым в чате, значение отсутствует.
 * @property branchB Флаг, указывающий, что в данный момент используется альтернативная ветка ответа.
 *                   Позволяет переключаться между несколькими вариантами продолжения диалога.
 * @property time Unix-метка времени (в миллисекундах) создания сообщения.
 * @property text Текстовое содержимое сообщения.
 * @property type Тип сообщения из перечисления [MessageType]: ввод пользователя, ответ бота, вызов
 *               инструмента, либо закреплённый системный факт.
 * @property tokens Количество токенов, затраченных на данное сообщение (как правило, оценка модели).
 * @property rank Ранг сообщения — количество выполненных "сжатий контекста", связанных с этим
 *                сообщением. У оригинальных (несжатых) сообщений ранг равен 0.
 * @property toolCallId Идентификатор вызова инструмента (опциональный), если сообщение связано
 *                      с вызовом внешней функции или плагина.
 * @property name Имя отправителя или название инструмента (опциональный), используется в зависимости
 *                от типа сообщения.
 */
data class ChatMessage(
    val id: UUID,
    val chatId: UUID,
    val parentId: UUID?,
    val branchB: Boolean, // показывает, что в данный момент используется альтернативная ветка
    val time: Long,
    val text: String,
    val type: MessageType,
    val tokens: Int,
    // ранг - количество "сжатий контекста", с которым связано данное сообщение. У оригинальных сообщений ранг: 0.
    val rank: Int,
    val toolCallId: String? = null,
    val name: String? = null,
)
