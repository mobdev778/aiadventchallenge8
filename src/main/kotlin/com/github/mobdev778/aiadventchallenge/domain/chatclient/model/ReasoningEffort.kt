package com.github.mobdev778.aiadventchallenge.domain.chatclient.model

/**
 * Уровень усилий, прилагаемых моделью для выполнения рассуждения.
 * Используется для настройки глубины анализа при генерации ответов в чат-клиенте.
 */
enum class ReasoningEffort {
    /**
     * Минимальные усилия, быстрый ответ.
     */
    Low,

    /**
     * Сбалансированный уровень усилий.
     */
    Medium,

    /**
     * Максимальные усилия, тщательное рассуждение.
     */
    High,
}
