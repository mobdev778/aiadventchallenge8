package com.github.mobdev778.aiadventchallenge.domain.agent.model

/**
 * Модель ответа, полученного от инструмента (tool) в рамках вызова агентом.
 *
 * Этот класс инкапсулирует результат выполнения конкретного инструмента,
 * связывая его с идентификатором исходного вызова. Используется в доменной
 * логике агента для обработки и маршрутизации ответов от внешних инструментов.
 *
 * @property toolCallId Уникальный идентификатор вызова инструмента, к которому относится данный ответ.
 *                      Позволяет сопоставить ответ с исходным запросом.
 * @property name Название инструмента, вернувшего данный ответ.
 * @property content Содержимое ответа, полученное в результате выполнения инструмента.
 */
data class ToolResponse(
    val toolCallId: String,
    val name: String,
    val content: String,
)
