package com.github.mobdev778.aiadventchallenge.domain.rag.ranker

/**
 * Эвристический ранкер, реализующий [Ranker] на основе совпадения подстрок.
 *
 * Алгоритм сравнивает множество всех подстрок запроса (представленных целочисленными хешами)
 * с подстроками найденного фрагмента. Чем больше доля совпавших подстрок, тем выше
 * релевантность фрагмента. Инициализация ([init]) выполняется один раз для запроса,
 * после чего метод [rank] может многократно вызываться для различных фрагментов.
 *
 * Векторное представление ([vector]) в данной реализации игнорируется — оценка строится
 * исключительно на символьных n-граммах.
 *
 * @see Ranker
 */
@Suppress("MagicNumber")
class HeuristicRanker : Ranker {

    /**
     * Множество хеш-кодов всех подстрок запроса, вычисляемых на этапе [init].
     * Используется в [rank] для проверки совпадений с подстроками найденного фрагмента.
     */
    val sourceHashes = HashSet<Int>()

    /**
     * Инициализирует ранкер для обработки указанного запроса.
     *
     * Проходит по всем символам запроса и строит множество хешей для каждой непрерывной
     * подстроки (от отдельных символов до всего запроса). Хеш вычисляется рекурсивно
     * по формуле `hash = previousHash * 31 + code`, что аналогично простому rolling-хешу.
     * Полученные значения сохраняются в [sourceHashes] для последующего сравнения.
     *
     * @param query текстовый запрос пользователя, для которого будут вычислены хеши
     *              всех подстрок
     */
    override suspend fun init(query: String) {
        val sequences = ArrayList<Seq>()
        for (c in query) {
            val code = c.code
            sequences.add(Seq())
            for (s in sequences) {
                s.hash = s.hash * 31 + code
                sourceHashes.add(s.hash)
            }
        }
    }

    /**
     * Вычисляет оценку релевантности найденного фрагмента путём сравнения его подстрок
     * с сохранёнными хешами запроса.
     *
     * Для каждого символа фрагмента обновляются хеши всех активных подстрок и проверяется
     * наличие полученного хеша в [sourceHashes]. Совпавшие подстроки увеличивают счётчик
     * `same`, а несовпавшие помечаются как неактивные (исключаются из дальнейшего рассмотрения).
     * Результат — доля совпавших подстрок от общего количества хешей запроса, что даёт
     * нормализованную оценку в диапазоне [0, 1].
     *
     * @param found текст найденного фрагмента документа-кандидата
     * @param vector векторное представление фрагмента (в данной реализации не используется)
     * @return оценка релевантности — отношение числа совпавших подстрок к общему количеству
     *         уникальных хешей запроса; чем выше значение, тем более релевантен фрагмент
     */
    override suspend fun rank(found: String, vector: FloatArray): Double {
        var same = 0

        val sequences = ArrayList<Seq>()
        for (c in found) {
            val code = c.code
            sequences.add(Seq())
            for (s in sequences) {
                s.hash = s.hash * 31 + code
                if (sourceHashes.contains(s.hash)) {
                    same++
                } else {
                    s.alive = false
                }
            }
        }
        for (i in sequences.size - 1 downTo 0) {
            if (!sequences[i].alive) {
                sequences.removeAt(i)
            }
        }
        return same.toDouble() / sourceHashes.size
    }
}

/**
 * Внутренний вспомогательный класс, представляющий одну подстроку в процессе вычисления
 * её хеша и отслеживания, продолжает ли она давать совпадения с исходным запросом.
 *
 * @param hash текущее значение хеша (обновляется при добавлении символа)
 * @param alive признак того, что подстрока ещё может совпадать с каким-либо хешем запроса;
 *              если на очередном шаге совпадения не найдено, флаг сбрасывается
 */
private class Seq(
    var hash: Int = 0,
    var alive: Boolean = true
)
