package com.github.mobdev778.aiadventchallenge.domain.mymcpserver

import com.github.mobdev778.aiadventchallenge.domain.mymcpserver.model.MyMcpServerState
import kotlinx.coroutines.flow.Flow

/**
 * Интерфейс, представляющий сервер MCP (MyMcpServer), позволяющий управлять его жизненным циклом
 * и отслеживать текущее состояние. Сервер может быть запущен и остановлен, а его состояние
 * транслируется через реактивный поток [observeState].
 *
 * Реализации этого интерфейса должны быть потокобезопасными и поддерживать корректную
 * обработку повторных вызовов `start()` / `stop()` (идемпотентность).
 */
interface MyMcpServer {

    /**
     * Возвращает холодный [Flow] с текущим и последующими значениями состояния сервера.
     *
     * Поток эмитит актуальное состояние при каждой подписке, а затем — все последующие
     * изменения (например, при вызове [start] или [stop]).
     *
     * @return поток состояний [MyMcpServerState], эмитирующий данные до тех пор, пока сборщик активен.
     */
    fun observeState(): Flow<MyMcpServerState>

    /**
     * Запускает сервер. Вызов является приостанавливаемым и возвращает управление
     * после успешного старта сервера.
     *
     * Если сервер уже запущен, повторный вызов не должен приводить к ошибке
     * (идемпотентность). В случае ошибки инициализации может бросить исключение.
     *
     * @throws IllegalStateException если сервер не может быть запущен из-за некорректного состояния.
     * @throws java.io.IOException если произошла ошибка ввода-вывода при старте (например, порт занят).
     */
    suspend fun start()

    /**
     * Останавливает сервер. Вызов приостанавливается до полной остановки всех ресурсов
     * и компонентов сервера. Гарантирует корректное завершение работы.
     *
     * Если сервер уже остановлен, повторный вызов не должен приводить к ошибке
     * (идемпотентность).
     */
    suspend fun stop()
}
