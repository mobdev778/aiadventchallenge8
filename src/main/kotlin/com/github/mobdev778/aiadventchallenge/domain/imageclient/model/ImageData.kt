package com.github.mobdev778.aiadventchallenge.domain.imageclient.model

/**
 * Модель данных, представляющая изображение в одном из двух возможных форматов:
 * либо в виде Base64-закодированной JSON-строки, либо в виде URL-адреса.
 *
 * Используется в слое предметной области для обмена данными изображений
 * между клиентом изображений и остальными компонентами системы.
 *
 * @property b64Json Base64-закодированная строка, содержащая JSON с данными изображения.
 *   Может быть `null`, если изображение передаётся через [url].
 * @property url URL-адрес, по которому доступно изображение.
 *   Может быть `null`, если изображение передаётся через [b64Json].
 */
data class ImageData(
    val b64Json: String? = null,
    val url: String? = null,
)
