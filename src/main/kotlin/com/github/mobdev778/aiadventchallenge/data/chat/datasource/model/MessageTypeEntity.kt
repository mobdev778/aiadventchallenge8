package com.github.mobdev778.aiadventchallenge.data.chat.datasource.model

/**
 * Перечисление типов сообщений, используемых в чате.
 *
 * Определяет возможные роли и категории сообщений в системе обмена данными между
 * пользователем и ассистентом. Каждый элемент перечисления соответствует
 * определённому участнику или служебному типу сообщения в рамках
 * conversational-интерфейса.
 */
enum class MessageTypeEntity {

    /** Сообщение, отправленное пользователем. */
    User,

    /** Ответное сообщение, сгенерированное ассистентом (AI). */
    Assistant,

    /** Сообщение, связанное с вызовом инструмента (tool call) или его результатом. */
    Tool,

    /** Закреплённые факты — служебный тип сообщения для хранения контекстных данных,
     *  сохраняющихся на протяжении сессии общения. */
    StickyFacts,
}
