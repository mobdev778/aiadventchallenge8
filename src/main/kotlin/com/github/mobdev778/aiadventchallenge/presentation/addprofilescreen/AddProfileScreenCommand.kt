package com.github.mobdev778.aiadventchallenge.presentation.addprofilescreen

/**
 * Запечатанный интерфейс, представляющий команды, которые могут быть отправлены
 * с экрана добавления профиля. Является частью презентационного слоя и
 * используется для передачи пользовательских действий (например, навигационных
 * намерений) в ViewModel или иной управляющий компонент экрана.
 *
 * Все возможные команды перечислены в виде вложенных объектов и классов данных,
 * что гарантирует типобезопасность и полноту обработки через `when`.
 */
sealed interface AddProfileScreenCommand {

    /**
     * Команда возврата на предыдущий экран.
     * Обрабатывается, например, нажатием системной кнопки "Назад" или аналогичным жестом.
     */
    data object Back : AddProfileScreenCommand
}
