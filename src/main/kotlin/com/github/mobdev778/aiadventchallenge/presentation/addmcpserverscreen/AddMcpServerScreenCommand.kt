 * Запечатанный интерфейс, представляющий команды, которые могут быть отправлены
 * с экрана добавления MCP-сервера. Используется в архитектуре для обработки
 * пользовательских действий и навигационных событий, связанных с этим экраном.
 *
 * Все возможные команды определены в виде вложенных объектов-наследников.
 */
sealed interface AddMcpServerScreenCommand {
    /**
     * Команда возврата назад. Сигнализирует о необходимости выйти
     * с экрана добавления MCP-сервера и вернуться на предыдущий экран.
     */
    data object Back : AddMcpServerScreenCommand
}
