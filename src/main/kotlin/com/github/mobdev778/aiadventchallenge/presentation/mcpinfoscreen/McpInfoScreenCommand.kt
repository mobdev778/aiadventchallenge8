package com.github.mobdev778.aiadventchallenge.presentation.mcpinfoscreen

/**
 * Запечатанный интерфейс, представляющий команды, которые могут быть отправлены
 * от UI-слоя экрана информации MCP к его ViewModel (или аналогичному компоненту).
 * Используется для инкапсуляции пользовательских действий в рамках данного экрана.
 * Является частью архитектурного паттерна "Команда" (Command) или MVI,
 * обеспечивая строгую типизацию и исчерпывающую обработку в `when`-выражениях.
 */
sealed interface McpInfoScreenCommand {
    /**
     * Команда навигации назад — вернуться с экрана информации MCP
     * на предыдущий экран или закрыть его.
     */
    data object Back : McpInfoScreenCommand
}
