package com.github.mobdev778.aiadventchallenge.presentation.addprofilescreen

/**
 * Запечатанный интерфейс, представляющий все возможные события,
 * которые могут произойти на экране добавления профиля.
 *
 * Используется в архитектуре, основанной на событиях (например, MVI или MVVM),
 * для передачи пользовательских действий от UI-слоя к ViewModel.
 * Каждая реализация описывает конкретное намерение пользователя
 * или изменение состояния интерфейса.
 */
sealed interface AddProfileScreenEvent {

    /**
     * Событие, возникающее при нажатии кнопки "Назад".
     * Инициирует навигацию возврата к предыдущему экрану.
     */
    data object OnBackClick : AddProfileScreenEvent

    /**
     * Событие, возникающее при изменении текста в поле ввода имени профиля.
     *
     * @param value Новое текстовое значение, введённое пользователем в поле имени.
     */
    data class OnNameChange(val value: String) : AddProfileScreenEvent

    /**
     * Событие, возникающее при изменении текста в поле ввода содержимого (описания) профиля.
     *
     * @param value Новое текстовое значение, введённое пользователем в поле содержимого.
     */
    data class OnContentChange(val value: String) : AddProfileScreenEvent

    /**
     * Событие, возникающее при нажатии кнопки "Добавить".
     * Инициирует процесс сохранения нового профиля с введёнными данными.
     */
    data object OnAddClick : AddProfileScreenEvent
}
