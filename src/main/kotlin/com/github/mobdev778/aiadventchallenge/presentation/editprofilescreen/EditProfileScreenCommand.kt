package com.github.mobdev778.aiadventchallenge.presentation.editprofilescreen

/**
 * Запечатанный интерфейс, представляющий набор команд (действий пользователя),
 * которые могут быть отправлены из UI-слоя экрана редактирования профиля
 * в ViewModel или другой управляющий компонент.
 *
 * Используется в паттерне "Команда" для централизованной обработки
 * пользовательских намерений и отделения логики навигации от слоя представления.
 */
sealed interface EditProfileScreenCommand {

    /**
     * Команда для возврата на предыдущий экран.
     * Обрабатывается навигационным компонентом для выполнения
     * операции "назад" (например, закрытие экрана или pop из back stack).
     */
    data object Back : EditProfileScreenCommand
}
